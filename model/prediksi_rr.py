# === Augmentasi Gaussian Noise untuk fitur RR ===

def add_gaussian_noise(data, mean=0.0, std=0.02):
    noise = np.random.normal(loc=mean, scale=std, size=data.shape)
    return np.clip(data + noise, 0, 1)

#buat data augmented
augmented_data = add_gaussian_noise(data_scaled)

#menggabungkan data asli + augment
