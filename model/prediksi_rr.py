# === K-Fold Cross Validation ===
from sklearn.metrics import mean_squared_error, mean_absolute_percentage_error, mean_absolute_error
from sklearn.model_selection import KFold

k = 5
kf = KFold(n_splits=k, shuffle=False)

train_rmse_scores = []
train_mape_scores = []
train_mae_scores = []

test_rmse_scores = []
test_mape_scores = []
test_mae_scores = []

fold = 1

for train_idx, test_idx in kf.split(X):
    X_train_fold, X_test_fold = X[train_idx], X[test_idx]
    y_train_fold, y_test_fold = y[train_idx], y[test_idx]

    # Bangun ulang model di setiap fold
    model = build_final_model()
    model.fit(X_train_fold, y_train_fold, epochs=100, verbose=0)

    # Prediksi
    y_train_pred = model.predict(X_train_fold)
    y_test_pred = model.predict(X_test_fold)

    # Inverse transform
    y_train_rescaled = scaler.inverse_transform(y_train_fold.reshape(-1, 1))
    y_test_rescaled = scaler.inverse_transform(y_test_fold.reshape(-1, 1))
    y_train_pred_rescaled = scaler.inverse_transform(y_train_pred)
    y_test_pred_rescaled = scaler.inverse_transform(y_test_pred)

    # Evaluasi
    train_rmse = np.sqrt(mean_squared_error(y_train_rescaled, y_train_pred_rescaled))
    train_mape = mean_absolute_percentage_error(y_train_rescaled, y_train_pred_rescaled)
    train_mae = mean_absolute_error(y_train_rescaled, y_train_pred_rescaled)

    test_rmse = np.sqrt(mean_squared_error(y_test_rescaled, y_test_pred_rescaled))
    test_mape = mean_absolute_percentage_error(y_test_rescaled, y_test_pred_rescaled)
    test_mae = mean_absolute_error(y_test_rescaled, y_test_pred_rescaled)

    # Simpan hasil
    train_rmse_scores.append(train_rmse)
    train_mape_scores.append(train_mape)
    train_mae_scores.append(train_mae)

    test_rmse_scores.append(test_rmse)
    test_mape_scores.append(test_mape)
    test_mae_scores.append(test_mae)

    print(f"\nFold {fold}:")
    print(f"Training MAPE : {train_mape * 100:.2f}%")
    print(f"Training MAE  : {train_mae:.2f}")
    print(f"Training RMSE : {train_rmse:.2f}")
    print(f"Testing MAPE  : {test_mape * 100:.2f}%")
    print(f"Testing MAE   : {test_mae:.2f}")
    print(f"Testing RMSE  : {test_rmse:.2f}")
    fold += 1

# === Rata-Rata Hasil Evaluasi ===
print("\n=== Rata-Rata Hasil Evaluasi LSTM dengan 5-Fold Cross Validation ===")
